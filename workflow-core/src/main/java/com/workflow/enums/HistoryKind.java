package com.workflow.enums;

/**
 * 历史记录的<b>内容类别</b>。
 *
 * <p>刻意做成可自由组合的集合，而不是 {@code NONE / ACTIVITY / FULL} 这样的"级别"：
 * 活动与任务两类记录之间<b>不存在递进关系</b> —— 只要任务历史（绩效统计）而不要活动历史
 * （路径还原）是完全合理的需求，用线性级别表达它反而会逼人接受多余的写入。
 *
 * <p>为什么需要开关：每一次节点推进都要写历史行，串行四节点流程跑完就是 6-8 行。
 * 审批量大了之后，历史写入会直接压在业务事务的临界路径上，
 * 高吞吐场景必须能选择只记必要的那一半。
 */
public enum HistoryKind {

    /** 活动历史（{@code wf_hist_activity}）：节点级区间，用于路径还原与环节耗时。 */
    ACTIVITY,

    /** 任务历史（{@code wf_hist_task}）：待办归属、实际处理人、结束原因。 */
    TASK
}
